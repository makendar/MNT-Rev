import { useEffect, useState } from "react";
import { Icon } from "../components/icons";
import { Avatar } from "../components/ui";
import { api } from "../lib/api";
import { useApp } from "../state";

const ROLE_LABEL = { owner: "Business owner view", manager: "Sales head view", rep: "Salesperson view" } as const;

export function Login() {
  const { signIn } = useApp();
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [demo, setDemo] = useState<{ name: string; email: string; role: keyof typeof ROLE_LABEL; title: string }[]>([]);

  useEffect(() => {
    api.get<typeof demo>("/auth/demo-accounts").then(setDemo).catch(() => {});
  }, []);

  async function submit(e?: React.FormEvent, creds?: { email: string; password: string }) {
    e?.preventDefault();
    setBusy(true);
    setError(null);
    try {
      await signIn(creds?.email ?? email, creds?.password ?? password);
    } catch (err) {
      setError((err as Error).message);
      setBusy(false);
    }
  }

  return (
    <div className="login">
      <div className="login-art">
        <div className="rings" />
        <div className="brand" style={{ padding: 0 }}>
          <div className="brand-mark">
            <Icon.Logo />
          </div>
          <div>
            <div className="brand-name">MNT Revenue</div>
            <div className="brand-sub">by MNT Analytics</div>
          </div>
        </div>
        <div className="login-copy">
          <div className="tag">Measure · Navigate · Transform</div>
          <h1>Know what needs attention next — and where your next revenue is coming from.</h1>
          <p className="lead">Sales pipeline, follow-up discipline, forecasting and explainable risk signals for growing B2B teams in India.</p>
          <div className="login-points">
            <div>
              <Icon.Check /> Every risk score and insight shows the evidence behind it.
            </div>
            <div>
              <Icon.Check /> Financial figures are calculated from your records — never generated by AI.
            </div>
            <div>
              <Icon.Check /> Start from Excel: import a CSV of deals in minutes.
            </div>
          </div>
        </div>
        <div className="foot">© MNT Analytics · Demo build — all data is fictional</div>
      </div>
      <div className="login-form">
        <div className="inner">
          <h1>Sign in</h1>
          <p className="muted mt-sm">Localhost demonstration with synthetic data for a fictional company.</p>
          <form className="stack mt" onSubmit={submit}>
            {error && <div className="error-box">{error}</div>}
            <div className="field">
              <label htmlFor="email">Work email</label>
              <input id="email" type="email" autoComplete="username" value={email} onChange={(e) => setEmail(e.target.value)} required />
            </div>
            <div className="field">
              <label htmlFor="pw">Password</label>
              <input id="pw" type="password" autoComplete="current-password" value={password} onChange={(e) => setPassword(e.target.value)} required />
            </div>
            <button className="btn btn-primary" disabled={busy} style={{ height: 38 }}>
              {busy ? "Signing in…" : "Sign in"}
            </button>
          </form>
          {demo.length > 0 && (
            <div className="mt" style={{ marginTop: 28 }}>
              <div className="small strong">Explore as a demo user</div>
              <div className="tiny muted">Password for all demo users: demo1234</div>
              <div className="demo-list">
                {demo.slice(0, 3).map((u) => (
                  <button key={u.email} className="demo-user" disabled={busy} onClick={() => submit(undefined, { email: u.email, password: "demo1234" })}>
                    <Avatar name={u.name} />
                    <div style={{ flex: 1 }}>
                      <div className="strong small">{u.name}</div>
                      <div className="tiny muted">
                        {u.title} · {ROLE_LABEL[u.role]}
                      </div>
                    </div>
                    <Icon.Arrow className="muted" />
                  </button>
                ))}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
