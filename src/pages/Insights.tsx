import { useState } from "react";
import { Link } from "react-router-dom";
import type { Insight } from "../../shared/types.ts";
import { Icon } from "../components/icons";
import { Empty, ErrorState, Loading, PageHead } from "../components/ui";
import { qs } from "../lib/api";
import { useApi } from "../lib/useApi";
import { useApp } from "../state";

interface InsightsData {
  insights: Insight[];
  briefing: string;
  briefingEngine: string;
  ai: { engine: string; label: string };
  generatedAt: string;
}

const SEVERITY_LABEL = { critical: "Act now", warning: "Watch", opportunity: "Opportunity", info: "Context" } as const;

export function Insights() {
  const { viewAs } = useApp();
  const { data, error, loading, reload } = useApi<InsightsData>(`/insights${qs({ owner: viewAs })}`);
  const [sev, setSev] = useState<string>("");

  if (error) return <ErrorState message={error} onRetry={reload} />;
  if (loading && !data) return <Loading />;
  if (!data) return null;
  const counts = data.insights.reduce<Record<string, number>>((m, i) => ({ ...m, [i.severity]: (m[i.severity] ?? 0) + 1 }), {});
  const list = data.insights.filter((i) => !sev || i.severity === sev);

  return (
    <>
      <PageHead title="Insights" subtitle="What changed, what's at risk and where the next opportunity is — with the evidence behind each point.">
        <button className="btn" onClick={reload} disabled={loading}>
          {loading ? "Refreshing…" : "Refresh"}
        </button>
      </PageHead>

      <section className="card card-pad briefing mb">
        <div className="row-between wrap">
          <div className="row">
            <Icon.Spark className="warn-text" />
            <h2>Briefing</h2>
          </div>
          <span className="tiny muted" title={data.ai.label}>
            Generated by: {data.briefingEngine === "rules" ? "rule-based engine" : data.briefingEngine} · {new Date(data.generatedAt).toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" })}
          </span>
        </div>
        <p className="mt-sm" style={{ fontSize: 14.5, lineHeight: 1.6, maxWidth: 980 }}>
          {data.briefing}
        </p>
      </section>

      <div className="tabs">
        <button className={`tab ${!sev ? "active" : ""}`} onClick={() => setSev("")}>
          All <span className="count">{data.insights.length}</span>
        </button>
        {(Object.keys(SEVERITY_LABEL) as (keyof typeof SEVERITY_LABEL)[]).map((s) => (
          <button key={s} className={`tab ${sev === s ? "active" : ""}`} onClick={() => setSev(s)}>
            {SEVERITY_LABEL[s]} <span className="count">{counts[s] ?? 0}</span>
          </button>
        ))}
      </div>

      {list.length === 0 ? (
        <div className="card">
          <Empty title="No insights in this category" />
        </div>
      ) : (
        <div className="stack">
          {list.map((i) => (
            <article key={i.id} className={`card insight ${i.severity}`}>
              <div className="bar" />
              <div>
                <div className="row wrap" style={{ gap: 8 }}>
                  <span className={`badge b-${i.severity}`}>{SEVERITY_LABEL[i.severity]}</span>
                  <span className="tiny muted" style={{ textTransform: "uppercase", letterSpacing: "0.06em" }}>
                    {i.category}
                  </span>
                </div>
                <h2 style={{ marginTop: 8 }}>{i.title}</h2>
                <p className="muted mt-sm" style={{ maxWidth: 900 }}>
                  {i.explanation}
                </p>
                {i.evidence.length > 0 && (
                  <div className="evidence">
                    {i.evidence.map((e, k) => (
                      <span key={k}>
                        {e.label}: <b>{e.value}</b>
                      </span>
                    ))}
                  </div>
                )}
                <div className="action-line">
                  <span className="lbl">Suggested</span>
                  <span>{i.action}</span>
                  {i.link && (
                    <Link to={i.link} className="btn btn-sm" style={{ marginLeft: "auto" }}>
                      Review <Icon.Arrow size={12} />
                    </Link>
                  )}
                </div>
              </div>
            </article>
          ))}
        </div>
      )}

      <p className="tiny muted mt">
        How this works: insights are produced by explicit rules over your stored deals, activities, follow-ups and targets (for example, “coverage below 3×” or “win rate 8+ points below average with at least 5 closed deals”). Figures are exact
        calculations, not model estimates. {data.ai.engine === "rules" ? "No language model is configured." : data.ai.label}
      </p>
    </>
  );
}
